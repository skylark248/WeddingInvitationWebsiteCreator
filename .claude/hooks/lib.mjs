// Shared helpers for the Claude Code hooks in this folder.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const PROJECT = process.env.CLAUDE_PROJECT_DIR
  ? path.resolve(process.env.CLAUDE_PROJECT_DIR)
  : path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');

/** The maintainer sets INVITE_MAINTAINER=1 (in .claude/settings.local.json → env) to lift the guards. */
export const isMaintainer = process.env.INVITE_MAINTAINER === '1';

export function readInput() {
  try {
    return JSON.parse(fs.readFileSync(0, 'utf8') || '{}');
  } catch {
    return {};
  }
}

/** Blocks the tool call: exit code 2 sends the message back to Claude. */
export function block(message) {
  process.stderr.write(message + '\n');
  process.exit(2);
}

/** Project-relative POSIX path, or null if the path is outside the project. */
export function projectPath(p) {
  if (!p) return null;
  const abs = path.resolve(PROJECT, p.replace(/^\/([a-z])\//i, '$1:/'));
  const rel = path.relative(PROJECT, abs);
  if (rel.startsWith('..') || path.isAbsolute(rel)) return null;
  return rel.split(path.sep).join('/');
}

// What the designer's Claude may change. Everything else in the project is the shared tool kit.
const EDITABLE = [
  /^invites\/[a-z0-9-]+\/theme\//,
  /^invites\/[a-z0-9-]+\/design\//,
  /^invites\/[a-z0-9-]+\/invite\.config\.json$/,
  /^invites\/[a-z0-9-]+\/PROGRESS\.md$/,
  /^invites\/[a-z0-9-]+\/proof\.txt$/,
  /^invites\/help-requests\//,
];

export function isEditable(rel) {
  return EDITABLE.some((re) => re.test(rel));
}

export function protectedReason(rel) {
  if (/^\.env$/.test(rel)) return 'The .env file holds private keys. Only the person types them in (Notepad), never Claude.';
  if (/^invites\/[a-z0-9-]+\/engine\//.test(rel)) {
    return `${rel} is this invite's frozen copy of the engine. Don't change it — make the change in the invite's theme/ (theme.css, theme.js, or a theme partial that overrides an engine one). If that's truly impossible, use /stuck.`;
  }
  if (/^invites\/[a-z0-9-]+\/dist\//.test(rel)) return `${rel} is generated by the build. Change the theme or config instead; the build rewrites dist/.`;
  return `${rel} is part of the shared tool kit (engine, scripts, checks, templates, examples, instructions). It is protected so one mistake can't break every invite or switch off a safety check. Make the change inside invites/<id>/theme/ or the invite's config instead. If the tool kit really needs changing, use /stuck so the maintainer can do it.`;
}
